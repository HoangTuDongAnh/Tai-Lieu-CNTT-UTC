public class PhuongTrinhModulo
{
    private long soDu;
    private long modulo;

    public PhuongTrinhModulo(long soDu, long modulo)
    {
        this.soDu = soDu;
        this.modulo = modulo;
    }

    public long getSoDu()
    {
        return soDu;
    }

    public long getModulo()
    {
        return modulo;
    }
}